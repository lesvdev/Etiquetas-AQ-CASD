/**
 * Genera una ficha informativa SVG en base64 de alta resolución para representar la etiqueta de laboratorio
 */
function createCardSvg(
  name: string,
  formula: string,
  cas: string,
  category: string,
  ghsList: string[],
  primaryColor: string,
  accentColor: string
): string {
  const ghsIconsSvg = ghsList
    .slice(0, 3)
    .map((ghs, i) => {
      const x = 50 + i * 140;
      return `
      <g transform="translate(${x}, 320)">
        <polygon points="45,0 90,45 45,90 0,45" fill="#ffffff" stroke="#dc2626" stroke-width="4"/>
        <text x="45" y="52" font-family="Arial, sans-serif" font-size="12" font-weight="bold" fill="#1e293b" text-anchor="middle">${ghs}</text>
      </g>
    `;
    })
    .join('');

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 600 480" width="100%" height="100%">
    <defs>
      <linearGradient id="grad-${cas.replace(/[^a-z0-9]/gi, '') || 'lab'}" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="${primaryColor}"/>
        <stop offset="100%" stop-color="${accentColor}"/>
      </linearGradient>
    </defs>
    
    <rect width="600" height="480" rx="16" fill="#ffffff" stroke="#e2e8f0" stroke-width="2"/>
    <path d="M 0 16 Q 0 0 16 0 L 584 0 Q 600 0 600 16 L 600 110 L 0 110 Z" fill="url(#grad-${cas.replace(/[^a-z0-9]/gi, '') || 'lab'})"/>
    
    <text x="32" y="42" font-family="Arial, sans-serif" font-size="12" font-weight="bold" fill="#ffffff" opacity="0.85" letter-spacing="1.5">FICHA TÉCNICA DE LABORATORIO • CASD</text>
    <text x="32" y="78" font-family="Arial, sans-serif" font-size="22" font-weight="800" fill="#ffffff">${name.slice(0, 32)}</text>
    <rect x="440" y="24" width="128" height="28" rx="14" fill="rgba(255,255,255,0.2)"/>
    <text x="504" y="43" font-family="Arial, sans-serif" font-size="11" font-weight="700" fill="#ffffff" text-anchor="middle">${category.slice(0, 16)}</text>
    
    <g transform="translate(32, 130)">
      <rect x="0" y="0" width="165" height="70" rx="10" fill="#f8fafc" stroke="#e2e8f0"/>
      <text x="16" y="24" font-family="Arial, sans-serif" font-size="11" font-weight="bold" fill="#64748b">FÓRMULA QUÍMICA</text>
      <text x="16" y="52" font-family="Courier, monospace" font-size="16" font-weight="bold" fill="#0f172a">${formula || 'N/D'}</text>
      
      <rect x="180" y="0" width="165" height="70" rx="10" fill="#f8fafc" stroke="#e2e8f0"/>
      <text x="196" y="24" font-family="Arial, sans-serif" font-size="11" font-weight="bold" fill="#64748b">NÚMERO CAS</text>
      <text x="196" y="52" font-family="Courier, monospace" font-size="15" font-weight="bold" fill="#0f172a">${cas || 'No asignado'}</text>
      
      <rect x="360" y="0" width="176" height="70" rx="10" fill="#f1f5f9" stroke="#cbd5e1"/>
      <text x="376" y="24" font-family="Arial, sans-serif" font-size="11" font-weight="bold" fill="#475569">ESTADO / PUREZA</text>
      <text x="376" y="52" font-family="Arial, sans-serif" font-size="13" font-weight="bold" fill="#1e293b">Grado Reactivo Lab</text>
    </g>
    
    <rect x="32" y="225" width="536" height="185" rx="12" fill="#fff1f2" stroke="#fecdd3"/>
    <text x="48" y="255" font-family="Arial, sans-serif" font-size="12" font-weight="bold" fill="#9f1239">CLASIFICACIÓN DE RIESGO &amp; PICTOGRAMAS GHS</text>
    ${ghsIconsSvg}
    
    <g transform="translate(32, 435)">
      <line x1="0" y1="0" x2="536" y2="0" stroke="#f1f5f9" stroke-width="1.5"/>
      <text x="0" y="24" font-family="Arial, sans-serif" font-size="11" fill="#94a3b8">Fotografía de referencia • Catálogo General de Laboratorio CASD</text>
      <text x="536" y="24" font-family="Courier, monospace" font-size="11" font-weight="bold" fill="#64748b" text-anchor="end">CASD-LAB</text>
    </g>
  </svg>`;

  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

